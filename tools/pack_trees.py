"""Packs Rex's forest trees (art/trees_src/*.png) into one picture, art/trees_atlas.png, and writes
the list of trees into scripts/tree_art.gd (between the "generated" markers).

Why one picture: the graphics card draws everything that uses the same picture in one go. With
every tree in its own file, a forest of mixed trees has to be drawn tree by tree (a thousand
separate draws); from one shared picture it goes in a handful. The darker copies (SHADES) are
for the inside of forests, for the same reason: tinting trees in the game splits the drawing up.

To add a tree: put its PNG in art/trees_src/ (one tree, transparent background, trunk at the
bottom middle), run   python3 tools/pack_trees.py   and add its name to the kind list in
scripts/tree.gd if you want to place it as a single tree too.
"""
import glob
import os
import re

import numpy as np
from PIL import Image

SRC = "art/trees_src"
ATLAS = "art/trees_atlas.png"
SCRIPT = "scripts/tree_art.gd"
WIDTH = 640
PAD = 2
# Each tree is stored again a little darker for the inside of forests (darkening with "modulate"
# in the game would stop the trees being drawn together). Shade 0 is the tree as drawn.
SHADES = [1.0, 0.92, 0.84, 0.76]
BEGIN = "# --- generated by tools/pack_trees.py: don't edit by hand ---"
END = "# --- end of generated part ---"


def trunk_base(im):
    """Where the trunk meets the ground: the bottom row, and the middle of the trunk a bit above
    the roots."""
    a = np.asarray(im)[:, :, 3] > 0
    h, w = a.shape
    yb = int(np.nonzero(a.any(1))[0].max())
    xs = []
    for y in range(int(yb - h * 0.16), int(yb - h * 0.07)):
        row = np.nonzero(a[y, w // 4: w * 3 // 4])[0]
        if len(row):
            xs.append(row.mean() + w // 4)
    return round(float(np.mean(xs))), yb


def main():
    files = sorted(glob.glob(os.path.join(SRC, "*.png")), key=lambda f: -Image.open(f).height)
    trees = [(os.path.splitext(os.path.basename(f))[0], Image.open(f).convert("RGBA")) for f in files]
    # shelf packing: rows of trees, tallest first
    x = y = row_h = 0
    places = []
    for name, im in trees:
        if x + im.width > WIDTH:
            x, y, row_h = 0, y + row_h + PAD, 0
        places.append((name, im, x, y))
        x += im.width + PAD
        row_h = max(row_h, im.height)
    step = y + row_h + PAD
    atlas = Image.new("RGBA", (WIDTH, step * len(SHADES)))
    lines = [f"const SHADE_STEP := {step}.0", f"const SHADE_COUNT := {len(SHADES)}", "const KINDS := {"]
    for name, im, px, py in places:
        for i, k in enumerate(SHADES):
            a = np.asarray(im).astype(float)
            a[:, :, :3] *= k
            atlas.paste(Image.fromarray(a.round().clip(0, 255).astype(np.uint8)), (px, py + i * step))
        bx, by = trunk_base(im)
        lines.append(f'\t"{name}": {{"region": Rect2({px}, {py}, {im.width}, {im.height}), '
                     f'"base": Vector2({bx}, {by})}},')
    lines.append("}")
    atlas.save(ATLAS, optimize=True)
    src = open(SCRIPT).read()
    block = BEGIN + "\n" + "\n".join(lines) + "\n" + END
    src = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda m: block, src, flags=re.S)
    open(SCRIPT, "w").write(src)
    print(f"{ATLAS}: {atlas.size}, {len(places)} trees x {len(SHADES)} shades")


if __name__ == "__main__":
    main()
